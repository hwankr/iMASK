UNKNOWN_SUBJECT = "기타"
UNKNOWN_KIND = "text"


def field_info(key: str) -> FieldInfo:
    """추출 키 → 대응. 표에 없는 키는 기타 개인정보·키 이름·기타·text·unknown."""
    info = FIELDS.get(key)
    if info is not None:
        return info
    return _f(UNKNOWN_CATEGORY, key, UNKNOWN_SUBJECT, UNKNOWN_KIND, "unknown")


def v2_grade(key: str) -> str | None:
    """설정 60 칸 키의 등급(상·중·하). 접두어가 없으면 None."""
    return V2_GRADE_PREFIXES.get(key[:2])


def v2_bare_key(key: str) -> str:
    """접두어를 뗀 칸 이름(접두어가 없으면 그대로)."""
    return key[2:] if key[:2] in V2_GRADE_PREFIXES else key


def v2_field_info(key: str, table: str | None = None) -> FieldInfo:
    """설정 60 칸 → 대응. 표를 주면 (표, 칸)으로, 안 주면 표 밖 칸 → 표 칸 순서로 찾는다.

    표에 없으면 접두어를 뗀 이름 · 기타 개인정보 · 기타 · text · unknown.
    """
    info = V2_TABLE_FIELDS.get((table, key)) if table is not None else (V2_FIELDS.get(key) or _V2_CELLS.get(key))
    if info is not None:
        return info
    return _f(UNKNOWN_CATEGORY, v2_bare_key(key), UNKNOWN_SUBJECT, UNKNOWN_KIND, "unknown")
